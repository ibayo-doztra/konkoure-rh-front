/** Deep-merge locale namespace modules into the base dictionaries. */
type Dict = Record<string, unknown>;
function deepMerge(base: Dict, extra: Dict): Dict {
  const out: Dict = { ...base };
  for (const [k, v] of Object.entries(extra)) {
    const prev = out[k];
    if (v && typeof v === "object" && !Array.isArray(v) && prev && typeof prev === "object") {
      out[k] = deepMerge(prev as Dict, v as Dict);
    } else {
      out[k] = v;
    }
  }
  return out;
}

const frResources = [frApp, frHrm, frTimeclock, frPerformance, frBilling, frPublic].reduce<Dict>(
  (acc, m) => deepMerge(acc, m as Dict),
  fr as unknown as Dict,
);
const enResources = [enApp, enHrm, enTimeclock, enPerformance, enBilling, enPublic].reduce<Dict>(
  (acc, m) => deepMerge(acc, m as Dict),
  en as unknown as Dict,
);

export const LANGUAGE_STORAGE_KEY = "konkoure.lang";

// One-off migration from the previous default detector key.
if (typeof window !== "undefined") {
  try {
    const legacy = window.localStorage.getItem("i18nextLng");
    if (legacy && !window.localStorage.getItem(LANGUAGE_STORAGE_KEY)) {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, legacy.slice(0, 2));
    }
  } catch {
    /* storage unavailable */
  }
}

function readStoredLanguage(): "fr" | "en" | null {
  if (typeof window === "undefined") return null;
  try {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY)?.slice(0, 2);
    return stored === "fr" || stored === "en" ? stored : null;
  } catch {
    return null;
  }
}

/**
 * Preference saved by the user. Read before `init`, which caches its initial
 * language ("fr") under the same key and would otherwise erase it.
 */
export const storedLanguage = readStoredLanguage();

if (!i18n.isInitialized) {
  i18n
    .use(LanguageDetector)
    .use(initReactI18next)
    .init({
      resources: { fr: { translation: frResources }, en: { translation: enResources } },
      // SSR and the browser must start with the same language. The persisted
      // preference is restored after hydration by HtmlLangSync.
      lng: "fr",
      defaultNS: "translation",
      ns: ["translation"],
      // No hard-coded `lng`: the detector restores the stored preference,
      // then falls back to the browser language, then to French.
      fallbackLng: "fr",
      supportedLngs: ["fr", "en"],
      load: "languageOnly",
      interpolation: { escapeValue: false },
      react: { useSuspense: false },
      detection: {
        // Keep SSR and the first browser render in French. A stored preference
        // still wins, but navigator detection caused hydration mismatches.
        order: ["localStorage"],
        caches: ["localStorage"],
        lookupLocalStorage: LANGUAGE_STORAGE_KEY,
      },
    });
}

/** Locale tag used for Intl date/number formatting. */
export function activeLocale(): string {
  const lng = (i18n.resolvedLanguage || i18n.language || "fr").slice(0, 2);
  return lng === "en" ? "en-GB" : "fr-FR";
}

/** Map an API error (06-api-reference error codes) to a translation key. */
export function authErrorKey(error: unknown): string {
  const { code, details } = (error ?? {}) as {
    code?: string;
    details?: { field?: string; rule?: string }[];
  };
  switch (code) {
    case "E_UNAUTHORIZED":
      return "auth.errors.invalidCredentials";
    case "E_CONFLICT":
      return "auth.errors.alreadyRegistered";
    case "E_ACCOUNT_LOCKED":
      return "auth.errors.accountLocked";
    case "E_PASSWORD_RESET_REQUIRED":
      return "auth.errors.passwordResetRequired";
    case "E_RATE_LIMITED":
      return "auth.errors.rateLimited";
    case "E_EMAIL_NOT_VERIFIED":
      return "auth.errors.emailNotConfirmed";
    case "E_VALIDATION": {
      // 06-api-reference §1: invalid link and password policy refusals.
      const detail = details?.[0];
      if (detail?.field === "token") return "auth.errors.invalidLink";
      if (detail?.rule === "composition") return "auth.errors.passwordComposition";
      if (detail?.rule === "common") return "auth.errors.passwordCommon";
      if (detail?.rule === "personal") return "auth.errors.passwordPersonal";
      return "auth.errors.invalidData";
    }
    case "E_NOT_FOUND":
      return "auth.errors.invalidLink";
    case "E_NETWORK":
      return "auth.errors.network";
    default:
      return "auth.errors.generic";
  }
}

