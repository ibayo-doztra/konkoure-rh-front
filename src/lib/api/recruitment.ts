// Job offers and public careers pages — 06-api-reference §8 and §11 (module `recruitment`).
import { keepPreviousData, queryOptions } from "@tanstack/react-query";
import { api, API_BASE_URL, ApiError } from "@/lib/api/client";
import type { ContractType } from "@/lib/api/hr";

export const JOBS_PAGE_SIZE = 20;

export type JobStatus = "draft" | "published" | "closed" | "archived";

/** A piece asked on top of the CV, which is always required. */
export interface RequiredDocument {
  /** `^[a-z][a-z0-9_]{0,39}$`, unique within the offer. */
  key: string;
  label: string;
  required: boolean;
}

export const MAX_REQUIRED_DOCUMENTS = 10;

export interface Job {
  id: string;
  title: string;
  /** Generated by the API, never changes. */
  slug: string;
  departmentId: string | null;
  location: string | null;
  contractType: ContractType;
  description: string | null;
  requirements: string | null;
  status: JobStatus;
  publishedAt: string | null;
  deadline: string | null;
  requiredDocuments: RequiredDocument[];
  inclusiveScore: number | null;
  viewsCount: number;
  createdAt: string;
  updatedAt: string;
}

export interface JobInput {
  title: string;
  contractType: ContractType;
  departmentId?: string | null;
  location?: string | null;
  description?: string | null;
  requirements?: string | null;
  /** ISO 8601. */
  deadline?: string | null;
  requiredDocuments?: RequiredDocument[];
}

export interface JobFilters {
  page: number;
  q?: string;
  status?: JobStatus;
}

export const JOB_STATUS_VARIANT: Record<
  JobStatus,
  "default" | "secondary" | "outline" | "destructive" | "success"
> = {
  draft: "secondary",
  published: "success",
  closed: "outline",
  archived: "outline",
};

export const recruitmentKey = (organizationId: string) =>
  ["org", organizationId, "recruitment"] as const;

export const jobsQuery = (organizationId: string, filters: JobFilters) =>
  queryOptions({
    queryKey: [...recruitmentKey(organizationId), "jobs", filters],
    queryFn: () =>
      api.list<Job>("/org/recruitment/jobs", {
        page: filters.page,
        perPage: JOBS_PAGE_SIZE,
        q: filters.q || undefined,
        "filter[status]": filters.status,
      }),
    placeholderData: keepPreviousData,
  });

export const jobQuery = (organizationId: string, id: string) =>
  queryOptions({
    queryKey: [...recruitmentKey(organizationId), "jobs", "detail", id],
    queryFn: () => api.get<Job>(jobPath(id)),
    retry: false,
  });

const jobPath = (id: string) => `/org/recruitment/jobs/${encodeURIComponent(id)}`;

/** Created in `draft`; the API generates the slug. */
export function createJob(input: JobInput) {
  return api.post<Job>("/org/recruitment/jobs", input);
}

export function updateJob(id: string, input: Partial<JobInput>) {
  return api.patch<Job>(jobPath(id), input);
}

/** `draft | closed → published`: needs a description and a future or empty deadline (422). */
export function publishJob(id: string) {
  return api.post<Job>(`${jobPath(id)}/publish`);
}

/** `published → closed`. */
export function closeJob(id: string) {
  return api.post<Job>(`${jobPath(id)}/close`);
}

/** A new draft copy. */
export function duplicateJob(id: string) {
  return api.post<Job>(`${jobPath(id)}/duplicate`);
}

/** Soft delete. */
export function deleteJob(id: string) {
  return api.delete(jobPath(id));
}

// ---------------------------------------------------------- Public careers pages (06 §11)

export interface PublicOrganization {
  name: string;
  slug: string;
  logoUrl: string | null;
}

export interface PublicJobSummary {
  slug: string;
  title: string;
  /** Department name. */
  department: string | null;
  location: string | null;
  contractType: ContractType;
  publishedAt: string | null;
  deadline: string | null;
}

export interface PublicJob extends PublicJobSummary {
  description: string | null;
  requirements: string | null;
  requiredDocuments: RequiredDocument[];
}

/** Null when the page is not visible: unknown slug, unpublished or expired offer (404). */
async function orNotFound<T>(request: Promise<T>): Promise<T | null> {
  try {
    return await request;
  } catch (e) {
    if (e instanceof ApiError && e.status === 404) return null;
    throw e;
  }
}

/** Published offers whose deadline has not passed. Public, no session. */
export function fetchCareersPage(orgSlug: string) {
  return orNotFound(
    api.get<{ organization: PublicOrganization; jobs: PublicJobSummary[] }>(
      `/public/careers/${encodeURIComponent(orgSlug)}`,
    ),
  );
}

export function fetchCareersJob(orgSlug: string, jobSlug: string) {
  return orNotFound(
    api.get<{ organization: PublicOrganization; job: PublicJob }>(
      `/public/careers/${encodeURIComponent(orgSlug)}/jobs/${encodeURIComponent(jobSlug)}`,
    ),
  );
}

// ------------------------------------------------------------ Public application (06 §11)

const applyPath = (orgSlug: string, jobSlug: string) =>
  `/public/careers/${encodeURIComponent(orgSlug)}/jobs/${encodeURIComponent(jobSlug)}/apply`;

/**
 * Duplicate check before any file is sent: same offer with the same e-mail
 * or phone gives `409` with the rule `already_applied`.
 */
export function checkApplication(
  orgSlug: string,
  jobSlug: string,
  input: { email: string; phone: string },
) {
  return api.post<{ available: true }>(`${applyPath(orgSlug, jobSlug)}/check`, input);
}

export interface ApplicationInput {
  fullName: string;
  email: string;
  /** `NNN NN NN NN`. */
  phone: string;
  cv: File;
  coverLetter?: File;
  /** Pieces of the offer by key. */
  documents: Record<string, File>;
}

/** Multipart. 410 closed or expired, 413 too large, 422 bad pieces, 429 too many attempts. */
export function submitApplication(orgSlug: string, jobSlug: string, input: ApplicationInput) {
  const body = new FormData();
  body.append("fullName", input.fullName);
  body.append("email", input.email);
  body.append("phone", input.phone);
  body.append("cv", input.cv);
  if (input.coverLetter) body.append("coverLetter", input.coverLetter);
  for (const [key, file] of Object.entries(input.documents)) body.append(`documents[${key}]`, file);
  // Honeypot (05 §4): always empty for a person.
  body.append("website", "");
  return api.post<{ candidateId: string; message: string }>(applyPath(orgSlug, jobSlug), body);
}

/** The duplicate rule of `/apply/check` and `/apply`. */
export const isAlreadyApplied = (e: unknown) =>
  e instanceof ApiError && e.status === 409 && e.details.some((d) => d.rule === "already_applied");

